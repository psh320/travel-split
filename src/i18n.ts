export const countLabel = (type: "group" | "expense" | "person", count: number) => {
  if (isKorean) {
    if (type === "person") return `${count}명`;
    if (type === "expense") return `${count}개 지출`;
    return `${count}개 그룹`;
  }

  if (type === "person") return `${count} ${count === 1 ? "person" : "people"}`;
  if (type === "expense")
    return `${count} ${count === 1 ? "expense" : "expenses"}`;
  return `${count} group${count === 1 ? "" : "s"}`;
};
